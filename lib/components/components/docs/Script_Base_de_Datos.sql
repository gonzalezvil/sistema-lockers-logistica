-- Sistema de Gestión de Lockers Logísticos
-- ============================================================

-- 0. LIMPIEZA PREVIA DE TABLAS (Evita conflictos al reejecutar)
DROP TABLE IF EXISTS tarea CASCADE;
DROP TABLE IF EXISTS movimiento CASCADE;
DROP TABLE IF EXISTS operario CASCADE;
DROP TABLE IF EXISTS envio CASCADE;
DROP TABLE IF EXISTS contacto_cliente CASCADE;
DROP TABLE IF EXISTS cliente CASCADE;
DROP TABLE IF EXISTS compartimento CASCADE;
DROP TABLE IF EXISTS punto_retiro CASCADE;

-- 1. TABLA: PUNTO_RETIRO
CREATE TABLE punto_retiro (
    codigo VARCHAR(20) PRIMARY KEY,
    direccion VARCHAR(200) NOT NULL,
    capacidad_maxima INTEGER NOT NULL CHECK (capacidad_maxima > 0)
);

-- 2. TABLA: COMPARTIMENTO
CREATE TABLE compartimento (
    id_compartimento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_identificacion VARCHAR(30) NOT NULL,
    tamano VARCHAR(10) NOT NULL CHECK (tamano IN ('chico', 'mediano', 'grande')),
    estado VARCHAR(20) NOT NULL DEFAULT 'libre' 
        CHECK (estado IN ('libre', 'ocupado', 'fuera de servicio')),
    codigo_punto VARCHAR(20) NOT NULL REFERENCES punto_retiro(codigo) ON DELETE CASCADE,
    ultima_revision TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    UNIQUE (codigo_punto, numero_identificacion)
);

-- 3. TABLA: CLIENTE
CREATE TABLE cliente (
    dni VARCHAR(15) PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL
);

-- 4. TABLA: CONTACTO_CLIENTE
CREATE TABLE contacto_cliente (
    id_contacto BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dni_cliente VARCHAR(15) NOT NULL REFERENCES cliente(dni) ON DELETE CASCADE,
    tipo_contacto VARCHAR(10) NOT NULL CHECK (tipo_contacto IN ('telefono', 'correo')),
    dato_contacto VARCHAR(150) NOT NULL,
    UNIQUE (dni_cliente, tipo_contacto, dato_contacto)
);

-- 5. TABLA: ENVIO
CREATE TABLE envio (
    numero_seguimiento VARCHAR(40) PRIMARY KEY,
    peso NUMERIC(8,2) NOT NULL CHECK (peso > 0),
    descripcion TEXT NOT NULL
);

-- 6. TABLA: OPERARIO
CREATE TABLE operario (
    legajo VARCHAR(20) PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL
);

-- 7. TABLA: MOVIMIENTO
CREATE TABLE movimiento (
    id_movimiento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_seguimiento VARCHAR(40) NOT NULL REFERENCES envio(numero_seguimiento),
    dni_cliente VARCHAR(15) NOT NULL REFERENCES cliente(dni),
    id_compartimento BIGINT NOT NULL REFERENCES compartimento(id_compartimento),
    codigo_origen VARCHAR(20) NOT NULL REFERENCES punto_retiro(codigo),
    codigo_destino VARCHAR(20) NOT NULL REFERENCES punto_retiro(codigo),
    fecha_hora_ingreso TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    fecha_hora_retiro TIMESTAMP WITH TIME ZONE,
    CHECK (fecha_hora_retiro IS NULL OR fecha_hora_retiro >= fecha_hora_ingreso)
);

-- 8. TABLA: TAREA
CREATE TABLE tarea (
    id_tarea BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_punto VARCHAR(20) NOT NULL REFERENCES punto_retiro(codigo) ON DELETE CASCADE,
    legajo_operario VARCHAR(20) NOT NULL REFERENCES operario(legajo),
    fecha TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    descripcion TEXT NOT NULL
);
